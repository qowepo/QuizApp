/// <summary>
/// Хранит правдоподобные заблуждения, относящиеся к конкретному вопросу.
/// </summary>
internal static class QuestionDistractorCatalog
{
    public static IReadOnlyList<string> Get(QuestionSeedData question)
    {
        var topicCatalog = question.Topic switch
        {
            Topic.CSharp => CSharp,
            Topic.EntityFramework => EntityFramework,
            Topic.RabbitMQ => RabbitMq,
            Topic.PostgreSQL => PostgreSql,
            Topic.Architecture => Architecture,
            _ => throw new ArgumentOutOfRangeException(
                nameof(question),
                question.Topic,
                "Unknown question topic.")
        };

        if (question.Sequence <= 0 ||
            question.Sequence > topicCatalog.Length)
        {
            throw new InvalidOperationException(
                $"Question {question.Id} has no distractor set.");
        }

        var distractors = topicCatalog[question.Sequence - 1];

        if (distractors.Length != 3 ||
            distractors.Any(string.IsNullOrWhiteSpace) ||
            distractors.Distinct(StringComparer.Ordinal).Count() != 3)
        {
            throw new InvalidOperationException(
                $"Question {question.Id} must contain three unique distractors.");
        }

        return distractors;
    }

